#!/usr/bin/env node
/**
 * One-off helper for the guild template: fetches official Blizzard media the
 * guild pages use and writes src/data/guild/wow/blizzard-media.json.
 *
 *  - Class icons: Game Data API, static-forever-us, /data/wow/media/playable-class/{id}
 *  - Instance tiles: Game Data API, static-us (retail journal; the forever
 *    namespace has no journal entries yet), /data/wow/media/journal-instance/{id}
 *
 * Not part of the 15-minute refresh. Re-run by hand when the config changes:
 *   BNET_CLIENT_ID=... BNET_CLIENT_SECRET=... node scripts/fetch-guild-media.mjs
 * Credentials and the access token are never printed.
 */
import { readFile, writeFile } from 'node:fs/promises';

const OUT = new URL('../src/data/guild/wow/blizzard-media.json', import.meta.url);
const CONFIG = new URL('../src/data/guild/wow/config.json', import.meta.url);
const HOST = 'https://us.api.blizzard.com';

function env(name) {
  const v = process.env[name];
  if (!v) { console.error(`Missing ${name}.`); process.exit(1); }
  return v;
}

async function token() {
  const basic = Buffer.from(`${env('BNET_CLIENT_ID')}:${env('BNET_CLIENT_SECRET')}`).toString('base64');
  const res = await fetch('https://oauth.battle.net/token', {
    method: 'POST',
    headers: { Authorization: `Basic ${basic}`, 'Content-Type': 'application/x-www-form-urlencoded' },
    body: 'grant_type=client_credentials',
  });
  const body = await res.json();
  if (!body.access_token) { console.error('Token request failed.'); process.exit(1); }
  return body.access_token;
}

async function get(path, t) {
  for (let i = 0; i < 5; i++) {
    const res = await fetch(`${HOST}${path}${path.includes('?') ? '&' : '?'}locale=en_US`, { headers: { Authorization: `Bearer ${t}` } });
    if (res.status === 429 || res.status >= 500) { await new Promise((r) => setTimeout(r, 500 * 2 ** i)); continue; }
    return res.ok ? res.json() : null;
  }
  return null;
}

const config = JSON.parse(await readFile(CONFIG, 'utf8'));
const t = await token();
const out = {
  note: 'Generated by scripts/fetch-guild-media.mjs from the Blizzard Game Data API. Do not edit by hand.',
  fetchedAt: new Date().toISOString(),
  classIcons: {},
  instanceTiles: {},
  sources: {
    classIcons: 'static-forever-us /data/wow/media/playable-class/{id}',
    instanceTiles: 'static-us /data/wow/media/journal-instance/{id} (retail journal artwork)',
  },
};
for (const c of config.classes) {
  const m = await get(`/data/wow/media/playable-class/${c.blizzardId}?namespace=static-forever-us`, t);
  const icon = m?.assets?.find((a) => a.key === 'icon')?.value ?? m?.assets?.[0]?.value;
  if (icon) out.classIcons[c.id] = icon;
  console.log(`class ${c.id}: ${icon ? 'ok' : 'missing'}`);
}
for (const inst of config.instances) {
  if (!inst.journalId) continue;
  const j = await get(`/data/wow/journal-instance/${inst.journalId}?namespace=static-us`, t);
  const m = await get(`/data/wow/media/journal-instance/${inst.journalId}?namespace=static-us`, t);
  const tile = m?.assets?.find((a) => a.key === 'tile')?.value;
  if (tile) out.instanceTiles[inst.id] = tile;
  console.log(`instance ${inst.id} (journal ${inst.journalId} = ${j?.name ?? '?'}): ${tile ? 'ok' : 'missing'}`);
}
await writeFile(OUT, `${JSON.stringify(out, null, 2)}\n`);
console.log('Wrote src/data/guild/wow/blizzard-media.json');
